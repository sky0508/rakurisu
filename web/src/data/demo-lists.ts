/** true にすると電話の下4桁を伏せる（公開ブースで実番号を出したくない時） */
export const MASK_PHONE: boolean = true;

export function maskPhone(value: string): string {
  if (!MASK_PHONE || !value) return value;
  const digits = value.replace(/\D/g, "");
  if (digits.length <= 4) return value;
  let masked = 0;
  return value
    .split("")
    .reverse()
    .map((ch) => {
      if (/\d/.test(ch) && masked < 4) {
        masked += 1;
        return "×";
      }
      return ch;
    })
    .reverse()
    .join("");
}

